#!/usr/bin/env node
// Applies SQL migrations and regenerates TypeScript types through the
// Supabase Management API.
//
//   node scripts/db.mjs status            list applied / pending migrations
//   node scripts/db.mjs migrate           apply pending files from supabase/migrations
//   node scripts/db.mjs types             regenerate src/lib/supabase/database.types.ts
//   node scripts/db.mjs sql "select 1"    run one query
//
// Needs SUPABASE_ACCESS_TOKEN (Account → Access Tokens) and SUPABASE_PROJECT_REF.
// Applied migrations are recorded in supabase_migrations.schema_migrations,
// the same table the Supabase CLI uses.

import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const ref = process.env.SUPABASE_PROJECT_REF ?? "osbcxscnvoejxpxjaldu";
const token = process.env.SUPABASE_ACCESS_TOKEN ?? "proxy-injected";
const api = `https://api.supabase.com/v1/projects/${ref}`;
const dir = path.resolve("supabase/migrations");

async function query(sql) {
  const res = await fetch(`${api}/database/query`, {
    method: "POST",
    headers: { authorization: `Bearer ${token}`, "content-type": "application/json" },
    body: JSON.stringify({ query: sql }),
  });
  const text = await res.text();
  if (!res.ok) throw new Error(`HTTP ${res.status}: ${text}`);
  return JSON.parse(text);
}

const quote = (s) => `'${s.replaceAll("'", "''")}'`;

async function applied() {
  await query(`
    create schema if not exists supabase_migrations;
    create table if not exists supabase_migrations.schema_migrations (
      version text primary key, statements text[], name text
    );`);
  const rows = await query("select version from supabase_migrations.schema_migrations");
  return new Set(rows.map((r) => r.version));
}

async function files() {
  return (await readdir(dir)).filter((f) => /^\d+_.+\.sql$/.test(f)).sort();
}

const [cmd, arg] = process.argv.slice(2);

if (cmd === "status" || cmd === "migrate") {
  const done = await applied();
  for (const file of await files()) {
    const [version, ...rest] = file.replace(/\.sql$/, "").split("_");
    if (done.has(version)) {
      console.log(`  applied  ${file}`);
      continue;
    }
    if (cmd === "status") {
      console.log(`  PENDING  ${file}`);
      continue;
    }
    const sql = await readFile(path.join(dir, file), "utf8");
    // One request = one transaction: the file and its record succeed or fail together.
    await query(`begin;\n${sql}\n;insert into supabase_migrations.schema_migrations (version, name, statements)
      values (${quote(version)}, ${quote(rest.join("_"))}, array[${quote(sql)}]);\ncommit;`);
    console.log(`  APPLIED  ${file}`);
  }
} else if (cmd === "types") {
  const res = await fetch(`${api}/types/typescript?included_schemas=public`, {
    headers: { authorization: `Bearer ${token}` },
  });
  if (!res.ok) throw new Error(`HTTP ${res.status}: ${await res.text()}`);
  const { types } = await res.json();
  const header = "// Generated by `node scripts/db.mjs types`. Do not edit by hand.\n\n";
  const aliases = `
export type Profile = Database["public"]["Tables"]["profiles"]["Row"];
export type UserRole = Database["public"]["Enums"]["user_role"];
`;
  const extra = await readFile("src/lib/supabase/type-aliases.ts", "utf8").catch(() => "");
  await writeFile("src/lib/supabase/database.types.ts", header + types + aliases + extra);
  console.log("  wrote src/lib/supabase/database.types.ts");
} else if (cmd === "sql") {
  console.log(JSON.stringify(await query(arg), null, 2));
} else {
  console.log("usage: node scripts/db.mjs status|migrate|types|sql <query>");
  process.exit(1);
}
